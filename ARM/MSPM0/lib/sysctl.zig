    mdiv: u4 = 0,
    udiv: u2 = 1,
    reserved: u2 = 0,
    flashwait: FlashWaitStates = .upto80Mhz,
    usemftick: bool = false,
    reserved2: u3 = 0,
    usemhfclk: bool = false,
    reserved3: u3 = 0,
    usemlfclk: bool = false,
    stopclkstby: bool = false,
    mclkdeadchk: bool = false,
    reserved4: u9 = 0
};

